CREATE OR REPLACE VIEW FLEET_RISK_HOTSPOTS AS
SELECT
    DRIVER_ID,
    AVG_SAFETY_SCORE,
    TOTAL_ALERTS,
    TOTAL_SESSIONS,
    ROUND(TOTAL_ALERTS / NULLIF(TOTAL_SESSIONS, 0), 2) AS ALERTS_PER_SESSION,
    PEAK_ESCALATION,
    CASE
        WHEN AVG_SAFETY_SCORE > 0.80 THEN 'CRITICAL - Immediate Coaching'
        WHEN AVG_SAFETY_SCORE > 0.60 THEN 'HIGH - Schedule This Week'
        WHEN AVG_SAFETY_SCORE > 0.40 THEN 'MEDIUM - Monitor Closely'
        WHEN TOTAL_ALERTS / NULLIF(TOTAL_SESSIONS, 0) > 5 THEN 'FREQUENT ALERTS - Review'
        ELSE 'NORMAL'
    END AS INTERVENTION_FLAG,
    CASE
        WHEN PEAK_ESCALATION >= 4 THEN TRUE
        ELSE FALSE
    END AS HAS_CRITICAL_INCIDENT
FROM DEMO_DB.PUBLIC.DRIVER_RISK_LEADERBOARD
WHERE AVG_SAFETY_SCORE > 0.40
   OR TOTAL_ALERTS / NULLIF(TOTAL_SESSIONS, 0) > 5
   OR PEAK_ESCALATION >= 4
ORDER BY AVG_SAFETY_SCORE DESC;
