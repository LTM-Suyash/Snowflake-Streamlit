CREATE OR REPLACE VIEW DRIVER_ALERT_PROFILE AS
SELECT
    DRIVER_ID,
    ALERT_TYPE,
    COUNT(*) AS TOTAL_OCCURRENCES,
    AVG(SEVERITY_SCORE) AS AVG_SEVERITY,
    MAX(SEVERITY_SCORE) AS MAX_SEVERITY,
    COUNT(DISTINCT SESSION_ID) AS SESSIONS_WITH_THIS_ALERT
FROM DEMO_DB.PUBLIC.REALTIME_ALERTS
WHERE DRIVER_ID IS NOT NULL
GROUP BY DRIVER_ID, ALERT_TYPE;

CREATE OR REPLACE VIEW DRIVER_DAILY_TREND AS
SELECT
    DRIVER_ID,
    DATE_TRUNC('day', TO_TIMESTAMP(SESSION_START_TS)) AS DAY,
    AVG(COMBINED_DRIVER_SAFETY_SCORE) AS AVG_SCORE,
    SUM(TOTAL_REALTIME_ALERTS) AS DAILY_ALERTS,
    COUNT(DISTINCT SESSION_ID) AS TRIPS,
    AVG(FATIGUE_SCORE) AS AVG_FATIGUE_SCORE,
    AVG(DISTRACTION_SCORE) AS AVG_DISTRACTION_SCORE,
    SUM(DURATION_SECONDS) AS TOTAL_DRIVING_SECONDS,
    MAX(ESCALATION_LEVEL) AS MAX_ESCALATION
FROM DEMO_DB.PUBLIC.UNIFIED_DRIVER_SESSION_SUMMARY
WHERE SESSION_START_TS IS NOT NULL
GROUP BY DRIVER_ID, DAY;

CREATE OR REPLACE VIEW DRIVER_HOURLY_FATIGUE AS
SELECT
    DRIVER_ID,
    HOUR(TO_TIMESTAMP(SESSION_START_TS)) AS HOUR_OF_DAY,
    AVG(FATIGUE_SCORE) AS AVG_FATIGUE,
    AVG(DISTRACTION_SCORE) AS AVG_DISTRACTION,
    COUNT(DISTINCT SESSION_ID) AS SESSION_COUNT,
    SUM(TOTAL_REALTIME_ALERTS) AS TOTAL_ALERTS_THIS_HOUR
FROM DEMO_DB.PUBLIC.UNIFIED_DRIVER_SESSION_SUMMARY
WHERE SESSION_START_TS IS NOT NULL
GROUP BY DRIVER_ID, HOUR_OF_DAY;

CREATE OR REPLACE VIEW DRIVER_WEEKLY_TREND AS
SELECT
    DRIVER_ID,
    DATE_TRUNC('week', TO_TIMESTAMP(SESSION_START_TS)) AS WEEK,
    AVG(COMBINED_DRIVER_SAFETY_SCORE) AS AVG_SCORE,
    SUM(TOTAL_REALTIME_ALERTS) AS WEEKLY_ALERTS,
    COUNT(DISTINCT SESSION_ID) AS TRIPS
FROM DEMO_DB.PUBLIC.UNIFIED_DRIVER_SESSION_SUMMARY
GROUP BY 1, 2;

CREATE OR REPLACE VIEW EVIDENCE_CLIP_BROWSE AS
SELECT
    e.CLIP_ID,
    e.SESSION_ID,
    e.DRIVER_ID,
    e.TRIP_ID,
    e.ALERT_TYPE,
    e.SEVERITY,
    e.EVENT_TIMESTAMP_SECONDS,
    e.DURATION_SECONDS,
    e.STAGE_PATH,
    e.FILE_SIZE_BYTES,
    a.MESSAGE AS ALERT_MESSAGE,
    a.ESCALATION_LEVEL,
    a.ZONE_AT_ALERT,
    a.CONFIDENCE,
    e.CREATED_AT
FROM DEMO_DB.PUBLIC.EVIDENCE_CLIP_INDEX e
LEFT JOIN DEMO_DB.PUBLIC.REALTIME_ALERTS a
    ON e.ALERT_ID = a.ALERT_ID
ORDER BY e.CREATED_AT DESC;

