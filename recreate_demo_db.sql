CREATE OR REPLACE DYNAMIC TABLE DRIVER_RISK_LEADERBOARD
    LAG = '1 hour'
    REFRESH_MODE = AUTO
    INITIALIZE = ON_CREATE
    WAREHOUSE = COMPUTE_WH
AS
SELECT
    DRIVER_ID,
    AVG(COMBINED_DRIVER_SAFETY_SCORE) AS AVG_SAFETY_SCORE,
    COUNT(DISTINCT SESSION_ID) AS TOTAL_SESSIONS,
    MAX(ESCALATION_LEVEL) AS PEAK_ESCALATION,
    SUM(TOTAL_REALTIME_ALERTS) AS TOTAL_ALERTS
FROM DEMO_DB.PUBLIC.UNIFIED_DRIVER_SESSION_SUMMARY
GROUP BY DRIVER_ID;

CREATE OR REPLACE DYNAMIC TABLE DRIVER_TOP_ALERT_TYPES
    LAG = '1 hour'
    REFRESH_MODE = AUTO
    INITIALIZE = ON_CREATE
    WAREHOUSE = COMPUTE_WH
AS
SELECT
    DRIVER_ID,
    ALERT_TYPE,
    TOTAL_OCCURRENCES,
    AVG_SEVERITY,
    ROW_NUMBER() OVER (PARTITION BY DRIVER_ID ORDER BY TOTAL_OCCURRENCES DESC) AS RANK
FROM DEMO_DB.PUBLIC.DRIVER_ALERT_PROFILE
QUALIFY RANK <= 3;

